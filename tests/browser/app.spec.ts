import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
const onePixelPng = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScdZpQAAAABJRU5ErkJggg==', 'base64')
test.beforeEach(async ({ page }) => { await page.addInitScript(() => localStorage.clear()) })
test('opens as a quiet, empty offline studio', async ({ page }) => {
  const external: string[] = []; page.on('request', (request) => { if (!request.url().startsWith('http://127.0.0.1')) external.push(request.url()) })
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Make a small world.' })).toBeVisible()
  await expect(page.getByText('There is no account, server, or AI in Pixelpaper.')).toBeVisible()
  await expect(page.getByText('Your shelf is empty.')).toBeAttached()
  expect(external).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect((await new AxeBuilder({ page }).analyze()).violations.map(v => v.id)).toEqual([])
})
test('draws a blank wallpaper and saves it locally', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'New wallpaper' }).click()
  await expect(page.getByRole('heading', { name: 'Draw it one pixel at a time.' })).toBeVisible()
  await expect(page.getByRole('application', { name: /Pixel canvas/ })).toBeVisible()
  await page.getByRole('button', { name: 'Use #f6c773' }).click()
  await page.getByRole('application', { name: /Pixel canvas/ }).click({ position: { x: 80, y: 60 } })
  await page.getByRole('button', { name: 'Save to shelf' }).click()
  await expect(page.getByText('Untitled pixel wall')).toBeVisible()
})
test('pixelates a dropped photo with the local algorithm', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Pixelate a photo' }).first().click()
  await page.locator('input[type=file]').setInputFiles({ name: 'tiny.png', mimeType: 'image/png', buffer: onePixelPng })
  await expect(page.getByRole('heading', { name: 'Turn a photo into pixels.' })).toBeVisible()
  await expect(page.getByText('Pixelated locally in your browser.')).toBeVisible({ timeout: 5000 })
  await expect(page.getByText('No cloud, no account, no AI.')).toBeVisible()
})
test('editor remains usable on a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 }); await page.goto('/')
  await page.getByRole('button', { name: 'New wallpaper' }).click()
  await expect(page.getByRole('combobox', { name: 'Color palette' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Color picker (I)' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
